#!/usr/bin/env node
/**
 * install-provider-config — splice the generated provider routes into a
 * profile's `cordis.patch.yml`, idempotently and with markers.
 *
 * The profile's patch layer replaces a row's `config` wholesale, so the
 * llm-pi-ai row must keep its existing providers beside the generated ones.
 * This script keeps every generated route inside ONE marked region, directly
 * after the row's last hand-written provider field, so a re-run rewrites that
 * region in place instead of appending a second copy. A region written by an
 * earlier generation of this tool (`dsh-commandcode provider`) is migrated.
 *
 * Usage:
 *   node tools/install-provider-config.mjs <profile-cordis.patch.yml> [--block <file>] [--check]
 *
 * @module dsh-plan-usage/tools/install-provider-config
 */

import { readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const DEFAULT_BLOCK = join(HERE, '..', 'provider', 'providers.yml')

const BEGIN = '      # >>> dsh-plan-usage providers — generated by tools/gen-provider-config.mjs, do not edit by hand'
const END = '      # <<< dsh-plan-usage providers'

/** Regions an earlier generation of this tool wrote; replaced when found. */
const LEGACY = [
  [
    '      # >>> dsh-commandcode provider — generated by tools/gen-provider-config.mjs, do not edit by hand',
    '      # <<< dsh-commandcode provider',
  ],
]

/** The line the region is inserted after when it is not present yet. */
const ANCHOR = '        apiKeyEnv: OPENCODE_GO_API_KEY'

const args = process.argv.slice(2)
const target = args.find((argument) => !argument.startsWith('--'))
const checkOnly = args.includes('--check')
const blockFlag = args.indexOf('--block')
const blockPath = blockFlag === -1 ? DEFAULT_BLOCK : args[blockFlag + 1]

if (target === undefined) {
  console.error('usage: install-provider-config.mjs <profile-cordis.patch.yml> [--block <file>] [--check]')
  process.exit(2)
}

const block = (await readFile(blockPath, 'utf8')).replace(/\s+$/, '')
const original = await readFile(target, 'utf8')
const region = `${BEGIN}\n${block}\n${END}`

/**
 * Replace one marked region.
 * @returns `{ text, found, changed }`.
 */
function replaceRegion(text, begin, end, replacement) {
  const start = text.indexOf(begin)
  if (start === -1) return { text, found: false, changed: false }
  const stop = text.indexOf(end, start)
  if (stop === -1) return { text, found: false, changed: false }
  const current = text.slice(start, stop + end.length)
  if (current === replacement) return { text, found: true, changed: false }
  return { text: text.replace(current, replacement), found: true, changed: true }
}

let next = original
let migrated = false
for (const [begin, end] of LEGACY) {
  const result = replaceRegion(next, begin, end, region)
  if (result.found === true) {
    next = result.text
    migrated = true
    break
  }
}

if (!migrated) {
  const result = replaceRegion(next, BEGIN, END, region)
  if (result.found === true) {
    next = result.text
  } else {
    const lines = next.split('\n')
    const anchor = lines.findIndex((line) => line === ANCHOR)
    if (anchor === -1) {
      console.error(`anchor not found in ${target}: ${JSON.stringify(ANCHOR)}`)
      process.exit(1)
    }
    lines.splice(anchor + 1, 0, region)
    next = lines.join('\n')
  }
}

if (next === original) {
  console.log(`unchanged: ${target}`)
  process.exit(0)
}
if (checkOnly) {
  console.error(`would change: ${target}`)
  process.exit(1)
}

// Temp + rename: the profile's patch layer is never read half-written, and the
// 0600 mode matches the file the harness writes for itself.
const temp = `${target}.install-${process.pid}.tmp`
await writeFile(temp, next, { mode: 0o600 })
await rename(temp, target)
console.log(`wrote the generated provider region into ${target}`)
